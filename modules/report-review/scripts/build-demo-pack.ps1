# Makes the review tool's demo pack (data/demo-pack.js) from one of the
# assessment tool's demos, through the same code as Send for review. The review
# tool only ever reads the file this writes: it needs nothing from the
# assessment tool at run time. Re-run after a change to the Word reports or the
# pack's shape, and commit the result.
#
#   .\modules\report-review\scripts\build-demo-pack.ps1
#   .\modules\report-review\scripts\build-demo-pack.ps1 -OutJson <path> -Id ncsc-caf [-Plain]
#
# -OutJson writes the pack as a plain JSON file instead, for trying things by hand.
param([string]$Id = "iec-62443-3-3", [string]$OutJson, [switch]$Plain)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$module = Split-Path -Parent $here
$repo = Split-Path -Parent (Split-Path -Parent $module)
$page = Join-Path $repo "modules\assessments\scripts\dump-review-pack.html"
$edge = "C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
$prof = Join-Path $env:TEMP ("edgeprof-" + [IO.Path]::GetRandomFileName())
$dump = Join-Path $env:TEMP ("review-pack-" + [IO.Path]::GetRandomFileName() + ".txt")
$q = "?id=$Id" + $(if ($Plain) { "" } else { "&demo=1" })
$url = "file:///" + $page.Replace('\', '/').Replace(' ', '%20') + $q
$p = Start-Process -FilePath $edge -NoNewWindow -PassThru -RedirectStandardOutput $dump -RedirectStandardError (Join-Path $env:TEMP "review-pack-err.txt") `
  -ArgumentList @("--headless=new", "--disable-gpu", "--no-first-run", "--disable-sync", "--allow-file-access-from-files", "--user-data-dir=`"$prof`"", "--virtual-time-budget=300000", "--dump-dom", "`"$url`"")
if (-not $p.WaitForExit(300000)) { try { $p.Kill() } catch {}; throw "The pack page timed out" }
$text = ""
for ($i = 0; $i -lt 120; $i++) { try { $text = [IO.File]::ReadAllText($dump); break } catch { Start-Sleep -Milliseconds 500 } }
Remove-Item $dump -Force -ErrorAction SilentlyContinue
try { Remove-Item $prof -Recurse -Force -ErrorAction Stop } catch {}
$m = [regex]::Match($text, '<pre id="pack">([A-Za-z0-9+/=]+)</pre>')
if (-not $m.Success) {
  $f = [regex]::Matches($text, '(?m)^FAIL.*$') | Select-Object -First 3
  throw "The pack page produced no pack. $($f -join ' ')"
}
$json = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($m.Groups[1].Value))
$utf8 = New-Object Text.UTF8Encoding($false)
if ($OutJson) {
  [IO.File]::WriteAllText($OutJson, $json, $utf8)
  Write-Output ("Wrote {0} ({1:N0} KB)" -f $OutJson, ($json.Length / 1KB))
  exit 0
}
$js = "/* Copyright (c) 2026 SolutionsPT. All rights reserved. Proprietary and confidential; licensed use only, see LICENCE.txt. */`n" +
  "// AUTO-GENERATED by scripts/build-demo-pack.ps1 from the assessment tool's $Id demo. Do not edit; re-run the script.`n" +
  "window.SPT_REVIEW_DEMO_PACK = " + $json + ";`n"
$out = Join-Path $module "data\demo-pack.js"
[IO.File]::WriteAllText($out, $js, $utf8)
Write-Output ("Wrote {0} ({1:N0} KB)" -f $out, ($js.Length / 1KB))
