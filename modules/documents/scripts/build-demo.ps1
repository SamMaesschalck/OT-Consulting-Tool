# Makes the tour's document (data/demo-document.js) from the Word fixture
# scripts/fixtures/demo-source.docx, through the tool's own importer in
# headless Edge (scripts/dump-demo.html). The demo is therefore a real import:
# a short proposal for an invented client with every block type, a diagram
# kept from Word and one line still to write. Re-run after a change to the
# importer, the project file's shape or the fixture, and commit the result.
#
#   .\modules\documents\scripts\build-demo.ps1
#   .\modules\documents\scripts\build-demo.ps1 -Check       # fails if the committed file is stale
#   .\modules\documents\scripts\build-demo.ps1 -OutJson <path>   # the project file itself, to open by hand
param([switch]$Check, [string]$OutJson)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$module = Split-Path -Parent $here
$page = Join-Path $here "dump-demo.html"
$edge = "C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
$prof = Join-Path $env:TEMP ("edgeprof-" + [IO.Path]::GetRandomFileName())
$dump = Join-Path $env:TEMP ("document-demo-" + [IO.Path]::GetRandomFileName() + ".txt")
$url = "file:///" + $page.Replace('\', '/').Replace(' ', '%20')
$p = Start-Process -FilePath $edge -NoNewWindow -PassThru -RedirectStandardOutput $dump -RedirectStandardError ($dump + ".err") `
  -ArgumentList @("--headless=new", "--disable-gpu", "--no-first-run", "--disable-sync", "--allow-file-access-from-files", "--user-data-dir=`"$prof`"", "--virtual-time-budget=300000", "--dump-dom", "`"$url`"")
if (-not $p.WaitForExit(300000)) { try { $p.Kill() } catch {}; throw "The demo page timed out" }
# The browser's helper processes can still be writing the dump when the main
# one exits, so keep looking until the page has said it is done.
$text = ""; $m = $null
for ($i = 0; $i -lt 120; $i++) {
  try { $text = [IO.File]::ReadAllText($dump) } catch { $text = "" }
  if ($text -match 'DEMO_DONE') { $m = [regex]::Match($text, '<pre id="demo">([A-Za-z0-9+/=]+)</pre>'); break }
  Start-Sleep -Milliseconds 500
}
Remove-Item -LiteralPath $dump, ($dump + ".err") -Force -ErrorAction SilentlyContinue
try { Remove-Item $prof -Recurse -Force -ErrorAction Stop } catch {}
$fails = @([regex]::Matches($text, '<p>(FAIL[^<]*)</p>') | ForEach-Object { $_.Groups[1].Value })
if ($fails.Count) { throw ("The demo was not made. " + ($fails -join " ")) }
if (-not $m -or -not $m.Success) { throw "The demo page printed no document." }
$json = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($m.Groups[1].Value))
$said = [regex]::Match($text, '<p>(DEMO [^<]*)</p>').Groups[1].Value
$utf8 = New-Object Text.UTF8Encoding($false)
if ($OutJson) {
  [IO.File]::WriteAllText($OutJson, $json, $utf8)
  Write-Output ("Wrote {0} ({1:N0} KB)" -f $OutJson, ($json.Length / 1KB))
  exit 0
}
$js = "/* Copyright (c) 2026 SolutionsPT. All rights reserved. Proprietary and confidential; licensed use only, see LICENCE.txt. */`n" +
  "// AUTO-GENERATED by scripts/build-demo.ps1 from scripts/fixtures/demo-source.docx, through the importer. Do not edit; re-run the script.`n" +
  "window.SPT_DOCUMENT_DEMO = " + $json + ";`n"
$out = Join-Path $module "data\demo-document.js"
if ($Check) {
  $now = if (Test-Path -LiteralPath $out) { [IO.File]::ReadAllText($out, $utf8) } else { "" }
  if ($now -cne $js) { Write-Output "STALE   data\demo-document.js. Run build-demo.ps1."; exit 1 }
  Write-Output "ok      data\demo-document.js"
  exit 0
}
[IO.File]::WriteAllText($out, $js, $utf8)
Write-Output ("Wrote {0} ({1:N0} KB). {2}" -f $out, ($js.Length / 1KB), $said)
