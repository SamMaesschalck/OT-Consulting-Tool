# Builds platform\data\suite-data.js, everything the suite's home page shows
# that comes from elsewhere in the repository:
#
#   - the tools, in suite.json order, each named by its own module.json, with
#     where to find it and its guided tour in the folder build
#   - the licence (platform\LICENCE.txt, synced from shared\LICENCE.txt)
#   - "What's new": the newest release notes, docs\releases\v<x.y.z>.md
#
#   .\platform\scripts\build-data.ps1            # rewrite data\suite-data.js
#   .\platform\scripts\build-data.ps1 -Check     # change nothing; exit 1 if it is out of date
#   .\platform\scripts\build-data.ps1 -OutFile <path>   # write it elsewhere (the suite's single-file build)
#
# Re-run it, and commit the result, after changing suite.json, a module's
# product name, the licence or the release notes. tools\release.ps1 runs it
# with -Check, and the single-file build always regenerates it.
param([switch]$Check, [string]$OutFile)

$ErrorActionPreference = "Stop"
$platform = Split-Path -Parent $PSScriptRoot
$repo = Split-Path -Parent $platform
$utf8 = New-Object System.Text.UTF8Encoding($false)
function ReadText($p) { return [IO.File]::ReadAllText($p, [Text.Encoding]::UTF8) }

$suite = ReadText (Join-Path $platform "suite.json") | ConvertFrom-Json

$modules = @()
foreach ($m in $suite.modules) {
  $dir = Join-Path $repo "modules\$($m.id)"
  $mf = Join-Path $dir "module.json"
  if (-not (Test-Path $mf)) { throw "suite.json lists '$($m.id)', but there is no modules\$($m.id)\module.json" }
  $info = ReadText $mf | ConvertFrom-Json
  $entry = "../modules/$($m.id)/$($info.entry)"
  $tour = $null
  if ($m.tour) {
    if ($m.tour.entry) {
      if (-not (Test-Path (Join-Path $dir $m.tour.entry))) { throw "The tour page modules\$($m.id)\$($m.tour.entry) named in suite.json does not exist" }
      # A page of its own: the single-file build carries it as a payload of its own.
      $tour = [ordered]@{ entry = "../modules/$($m.id)/$($m.tour.entry)"; payload = "$($m.id)-tour"; launch = $null }
    } else {
      # The tool's own page, opened with launch options.
      $tour = [ordered]@{ entry = $entry; payload = $m.id; launch = $m.tour.launch }
    }
    $tour.label = [string]$m.tour.label
    $tour.note = [string]$m.tour.note
  }
  $modules += [ordered]@{
    id = $m.id; name = [string]$info.product; shortName = [string]$m.shortName
    summary = [string]$m.summary; useWhen = [string]$m.useWhen
    entry = $entry; payload = $m.id; tour = $tour
  }
}

# The newest release notes, by version number.
$notesDir = Join-Path $repo "docs\releases"
$notes = Get-ChildItem $notesDir -Filter "v*.md" -ErrorAction SilentlyContinue |
  Where-Object { $_.Name -match '^v(\d+)\.(\d+)\.(\d+)\.md$' } |
  Sort-Object { $v = [regex]::Match($_.Name, '^v(\d+)\.(\d+)\.(\d+)'); [int]$v.Groups[1].Value * 1000000 + [int]$v.Groups[2].Value * 1000 + [int]$v.Groups[3].Value } |
  Select-Object -Last 1
if (-not $notes) { throw "No release notes in docs\releases (expected v<x.y.z>.md)" }
$notesVersion = [regex]::Match($notes.Name, '^v(\d+\.\d+\.\d+)').Groups[1].Value
$p = $notesVersion.Split('.')
$notesLabel = "v" + $(if ($p[2] -eq "0") { $p[0] + "." + $p[1] } else { $notesVersion })

$data = [ordered]@{
  product = [string]$suite.product
  shortName = [string]$suite.shortName
  modules = $modules
  licence = (ReadText (Join-Path $platform "LICENCE.txt")).Replace("`r`n", "`n").TrimEnd()
  releaseNotes = [ordered]@{
    version = $notesVersion; label = $notesLabel; file = "docs/releases/$($notes.Name)"
    markdown = (ReadText $notes.FullName).Replace("`r`n", "`n").TrimEnd()
  }
}

$json = ConvertTo-Json -InputObject $data -Depth 8
$js = "/* Copyright (c) 2026 SolutionsPT. All rights reserved. Proprietary and confidential; licensed use only, see LICENCE.txt. */`n" +
  "// AUTO-GENERATED by platform/scripts/build-data.ps1 from suite.json, each module's module.json,`n" +
  "// LICENCE.txt and the newest docs/releases/v*.md. Do not edit; re-run the script.`n" +
  "window.Suite = window.Suite || {};`n" +
  "window.Suite.Data = " + $json.Replace("`r`n", "`n") + ";`n"

$target = if ($OutFile) { $OutFile } else { Join-Path $platform "data\suite-data.js" }
if ($Check) {
  $current = if (Test-Path $target) { ReadText $target } else { "" }
  if ($current -ne $js) { Write-Output "platform\data\suite-data.js is out of date. Run platform\scripts\build-data.ps1 and commit it."; exit 1 }
  Write-Output "platform\data\suite-data.js is up to date (release notes $notesLabel)."
  exit 0
}
New-Item -ItemType Directory -Force (Split-Path -Parent $target) | Out-Null
[IO.File]::WriteAllText($target, $js, $utf8)
Write-Output ("Wrote {0}: {1} tools, release notes {2}." -f $target, $modules.Count, $notesLabel)
